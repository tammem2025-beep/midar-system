#!/usr/bin/env python3
"""Build M's single runtime stylesheet from ordered source modules.

Run from the repository root: python tools/build_frontend_css.py
The module order intentionally matches the historic 0.12.0 cascade. Avoid
reordering modules unless a visual-regression check has been completed.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "frontend" / "styles-src"
OUTPUT = ROOT / "frontend" / "midar-ui.css"
MODULES = [
    "00-foundation.css",
    "01-theme.css",
    "02-visual-upgrade.css",
    "03-settings-enhanced.css",
    "04-premium-settings.css",
    "05-experience.css",
    "06-premium-experience.css",
    "07-visual-redesign.css",
    "08-dashboard-command.css",
    "09-premium-shell.css",
    "10-content-calendar.css",
    "11-sidebar-redesign.css",
    "12-cross-platform.css",
    "13-design-system.css",
    "14-m-brand-identity.css",
    "15-social-hub-premium.css",
]

VERSION = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
parts = [f"/* M — Digital Business Management {VERSION} runtime CSS bundle. Generated from frontend/styles-src; do not edit this file directly. */\n"]
for name in MODULES:
    path = SOURCE_DIR / name
    if not path.is_file():
        raise SystemExit(f"Missing CSS source module: {path}")
    parts.append(f"\n/* ===== BEGIN {name} ===== */\n")
    parts.append(path.read_text(encoding="utf-8"))
    parts.append(f"\n/* ===== END {name} ===== */\n")
OUTPUT.write_text("".join(parts), encoding="utf-8", newline="\n")
print(f"Built {OUTPUT.relative_to(ROOT)} from {len(MODULES)} modules ({OUTPUT.stat().st_size:,} bytes).")
